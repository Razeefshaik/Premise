"""Phase 1 evaluation on the hand labelled fixture corpus.

Honest caveat (also written into the report): the corpus is small and was written alongside the
extractor, so these numbers are optimistic. They prove the mechanics, not real world accuracy.
"""
from __future__ import annotations

import uuid
from pathlib import Path

import redis
import yaml

from premise.graph.client import GraphClient

from .extract import Claim, ground
from .pipeline import Pipeline, fixture_workers
from .registry import Ext


def _probe_grounding(ext: Ext) -> dict:
    """Fabricated claims an LLM extractor might produce; every one must be rejected."""
    text = "FYI Paylane now retries webhooks for 72 hours. Their changelog went out this morning."
    base = dict(id="probe", fact="paylane.retry_window_hours", unit="hours", previous=None, status="asserted",
                supersedes=True, envelope_key="probe", sequence=1, as_of_ms=0, person="probe")
    probes = {
        "quote_not_in_source": Claim(value=96, raw="96 hours", quote="Paylane now retries webhooks for 96 hours.",
                                     start=4, end=46, **base),
        "value_not_in_quote": Claim(value=72, raw="72 hours", quote="Their changelog went out this morning.",
                                    start=48, end=86, **base),
        "fact_not_in_quote": Claim(value=72, raw="72 hours", quote="webhooks for 72 hours.", start=24, end=46, **base),
        "value_mismatch": Claim(value=48, raw="72 hours", quote="FYI Paylane now retries webhooks for 72 hours.",
                                start=0, end=46, **base),
    }
    results = {name: ground(c, text, ext) for name, c in probes.items()}
    return {"probes": len(probes), "rejected": sum(not ok for ok, _ in results.values()),
            "reasons": {name: why for name, (_, why) in results.items()}}


def run_eval(r: redis.Redis, host: str, port: int, model_root: str, fixtures: str) -> dict:
    expected = yaml.safe_load((Path(fixtures) / "expected.yaml").read_text(encoding="utf-8"))
    tag = uuid.uuid4().hex[:8]
    staging = GraphClient(host, port, f"premise_v2_eval_staging_{tag}")
    decision = GraphClient(host, port, f"premise_v2_eval_decision_{tag}")
    stream = f"premise:v2:eval:{tag}"
    try:
        p = Pipeline(r, staging, decision, model_root, fixture_workers(fixtures), out_dir=None, stream_name=stream)
        summary = p.run()
        rows = staging.read("MATCH (c:Claim) RETURN c.envelope_key AS k, c.fact AS f, c.value AS v, c.status AS s, c.grounded AS g")
        got = {(x["k"], x["f"], x["v"], x["s"]) for x in rows if x["g"]}
        want = {(k, f, v, s) for k, item in expected["items"].items() for f, v, s in item["claims"]}
        tp = len(got & want)
        drift_got = {(d["fact"], d["to"], d["support"], d["contested"]) for d in summary.drifts}
        drift_want = {(d["fact"], d["to"], d["support"], d["contested"]) for d in expected["drifts"]}
        decoys = {k for k, item in expected["items"].items() if all(s != "asserted" for _, _, s in item["claims"])}
        asserted_want = {w for w in want if w[3] == "asserted"}
        asserted_got = {g for g in got if g[3] == "asserted"}
        return {
            "corpus": {"items": len(expected["items"]), "labelled_claims": len(want)},
            "claims": {"extracted": len(got), "correct": tp,
                       "precision": round(tp / len(got), 3) if got else None,
                       "recall": round(tp / len(want), 3) if want else None,
                       "asserted_precision": round(len(asserted_got & asserted_want) / len(asserted_got), 3) if asserted_got else None,
                       "missed": sorted(map(list, want - got)), "unexpected": sorted(map(list, got - want))},
            "decoys_promoted_to_support": len(decoys & {k for dr in summary.drifts for group in dr["origins"] for k in group}),
            "decoys": len(decoys),
            "drift": {"expected": len(drift_want), "found": len(drift_got), "true_positive": len(drift_got & drift_want),
                      "false_positive": len(drift_got - drift_want)},
            "proposals": [x["key"] for x in summary.proposals if x["state"] != "skipped"],
            "redactions": {"expected": expected["redactions"], "found": summary.redactions},
            "grounding_probes": _probe_grounding(Ext.load(model_root)),
            "stream": summary.stream,
        }
    finally:
        staging.delete_graph()
        decision.delete_graph()
        r.delete(stream, f"{stream}:dead", f"{stream}:failures")


def write_markdown(report: dict, path: str) -> None:
    c, d, g = report["claims"], report["drift"], report["grounding_probes"]
    lines = [
        "# Premise v2 Phase 1 evaluation", "",
        "Generated by `premise-v2 eval` on the hand labelled corpus in `fixtures/v2/` "
        f"({report['corpus']['items']} items, {report['corpus']['labelled_claims']} labelled claims).", "",
        "**Caveat:** the corpus is small and was written alongside the extractor, so these numbers are optimistic. "
        "They show the mechanics work end to end; they are not a measure of accuracy on real company chat.", "",
        "| Measure | Result |", "| --- | --- |",
        f"| Claim precision (claim, value and status all correct) | {c['precision']} |",
        f"| Claim recall | {c['recall']} |",
        f"| Precision of asserted claims | {c['asserted_precision']} |",
        f"| Drift true positives / expected | {d['true_positive']} / {d['expected']} |",
        f"| Drift false positives | {d['false_positive']} |",
        f"| Decoy items (joke, denial, injected instruction, unrelated retry, no claim) promoted to drift support | "
        f"{report['decoys_promoted_to_support']} of {report['decoys']} |",
        f"| Secrets redacted / expected | {report['redactions']['found']} / {report['redactions']['expected']} |",
        f"| Fabricated claims rejected by the grounding gate | {g['rejected']} / {g['probes']} |",
        f"| Proposals | {', '.join(report['proposals']) or 'none'} |", "",
        "Grounding probe reasons: " + ", ".join(f"{k} → {v}" for k, v in g["reasons"].items()), "",
    ]
    if c["missed"] or c["unexpected"]:
        lines += ["Missed: " + str(c["missed"]), "", "Unexpected: " + str(c["unexpected"]), ""]
    Path(path).write_text("\n".join(lines), encoding="utf-8")
